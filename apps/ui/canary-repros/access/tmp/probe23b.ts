import { chromium } from "playwright";
const BASE = "https://canary.smithers.sh";
const ctx = await chromium.launchPersistentContext("/tmp/canary-access-profile", { headless: true, viewport: { width: 1280, height: 1000 } });
const page = ctx.pages()[0] ?? await ctx.newPage();
await page.goto("about:blank");
const client = await ctx.newCDPSession(page);
await client.send("Storage.clearDataForOrigin", { origin: BASE, storageTypes: "file_systems,local_storage,indexeddb,cache_storage,websql,service_workers" });
await client.detach().catch(()=>{});
const jar = await ctx.cookies();
await ctx.clearCookies();
await ctx.addCookies(jar.filter(c => !c.domain.includes("smithers.sh")));
await page.goto(`${BASE}/api/auth/github/callback?error=access_denied&error_description=The+user+has+denied+your+application+access.&state=zzz`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(1500);
console.log("DENIAL PAGE:\n" + (await page.locator("body").innerText()));
await page.locator('a:has-text("Back to Smithers")').first().click();
await page.waitForTimeout(5000);
console.log("BACK URL:", page.url());
console.log("SESSION:", JSON.stringify(await page.evaluate(async () => (await fetch("/api/auth/session")).json())));
console.log("BODY:\n" + (await page.locator("body").innerText()).slice(0,400));
await page.locator('[data-flow="auth.sign-in"]').last().click();
await page.waitForTimeout(10000);
console.log("SIGNED IN:", JSON.stringify(await page.evaluate(async () => (await fetch("/api/auth/session")).json())));
const before = await ctx.cookies();
console.log("COOKIE NAMES:", before.filter(c=>c.domain.includes("smithers")).map(c=>`${c.name}@${c.domain}`).join(","));
await ctx.clearCookies();
await ctx.addCookies(before.filter(c => !c.domain.includes("smithers.sh")));
await page.locator("textarea.sui-chat-composer-input").click();
await page.keyboard.type("list my open issues", { delay: 5 });
await page.keyboard.press("Enter");
await page.waitForTimeout(15000);
console.log("---AFTER ACTION WITH DELETED COOKIE---\n" + (await page.locator("body").innerText()).slice(-2500));
console.log("FLOWS", JSON.stringify(await page.evaluate(() => Array.from(document.querySelectorAll("[data-flow]")).map(n => n.getAttribute("data-flow")))));
await page.screenshot({ path: "/tmp/canary-access/2.6-expired.png", fullPage: true });
await ctx.close();
