import { chromium } from "playwright";
const BASE = "https://canary.smithers.sh";
const ctx = await chromium.launchPersistentContext("/tmp/canary-access-profile", { headless: true, viewport: { width: 1280, height: 900 } });
const page = ctx.pages()[0] ?? await ctx.newPage();
await page.goto("about:blank");
const client = await ctx.newCDPSession(page);
await client.send("Storage.clearDataForOrigin", { origin: BASE, storageTypes: "file_systems,local_storage,indexeddb,cache_storage,websql,service_workers" });
await client.detach().catch(()=>{});
const jar = await ctx.cookies();
await ctx.clearCookies();
await ctx.addCookies(jar.filter(c => !c.domain.includes("smithers.sh")));
const tab1 = page;
await tab1.goto(BASE, { waitUntil: "domcontentloaded" });
await tab1.waitForTimeout(3000);
const tab2 = await ctx.newPage();
await tab2.goto(BASE, { waitUntil: "domcontentloaded" });
await tab2.waitForTimeout(3000);
console.log("tab1 signed out?", (await tab1.locator("body").innerText()).includes("design-partner preview"));
await tab2.locator('[data-flow="auth.sign-in"]').last().click();
await tab2.waitForTimeout(12000);
console.log("tab2 session:", JSON.stringify(await tab2.evaluate(async () => (await fetch("/api/auth/session")).json())));
for (const wait of [5000, 10000, 15000]) {
  await tab1.waitForTimeout(wait === 5000 ? 5000 : 10000);
  const t = await tab1.locator("body").innerText();
  console.log(`tab1 after ~${wait}ms: signedOutCopy=${t.includes("design-partner preview")} digest=${t.includes("open issues")}`);
}
await tab1.screenshot({ path: "/tmp/canary-access/2.5-tab1.png", fullPage: true });
const t1 = await tab1.locator("body").innerText();
console.log("--- TAB1 FINAL ---\n" + t1.slice(0,900));
// reverse: sign out in tab1, does tab2 follow?
await tab1.locator("textarea.sui-chat-composer-input").click().catch(()=>{});
await tab1.keyboard.type("/auth.sign-out", { delay: 10 });
await tab1.keyboard.press("Enter");
await tab1.waitForTimeout(4000);
console.log("tab1 session after signout:", JSON.stringify(await tab1.evaluate(async () => (await fetch("/api/auth/session")).json())));
await tab2.waitForTimeout(20000);
const t2 = await tab2.locator("body").innerText();
console.log(`tab2 after signout in tab1: signedOutCopy=${t2.includes("design-partner preview")} digest=${t2.includes("open issues")}`);
await tab2.screenshot({ path: "/tmp/canary-access/2.5-tab2.png", fullPage: true });
console.log("--- TAB2 FINAL ---\n" + t2.slice(0,700));
await ctx.close();
