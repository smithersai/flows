import { chromium } from "playwright";
const BASE = "https://canary.smithers.sh";
const ctx = await chromium.launchPersistentContext("/tmp/canary-access-profile", { headless: true, viewport: { width: 1280, height: 1000 } });
const page = ctx.pages()[0] ?? await ctx.newPage();
await page.goto("about:blank");
const client = await ctx.newCDPSession(page);
await client.send("Storage.clearDataForOrigin", { origin: BASE, storageTypes: "file_systems,local_storage,indexeddb,cache_storage,websql,service_workers" });
await client.detach().catch(()=>{});
const jar = await ctx.cookies();
await ctx.clearCookies();
await ctx.addCookies(jar.filter(c => !c.domain.includes("smithers.sh")));
await page.goto(BASE, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(3000);
await page.locator('[data-flow="auth.sign-in"]').last().click();
await page.waitForTimeout(12000);
console.log("SIGNED IN:", JSON.stringify(await page.evaluate(async () => (await fetch("/api/auth/session")).json())));
const signedInBody = await page.locator("body").innerText();
console.log("--- SIGNED IN BODY (tail) ---\n" + signedInBody.slice(-1200));
// sign out
const composer = page.locator("textarea.sui-chat-composer-input");
await composer.click();
await page.keyboard.type("/auth.sign-out", { delay: 10 });
await page.keyboard.press("Enter");
await page.waitForTimeout(6000);
console.log("SESSION AFTER SIGNOUT:", JSON.stringify(await page.evaluate(async () => (await fetch("/api/auth/session")).json())));
console.log("--- AFTER SIGNOUT (no reload) ---\n" + (await page.locator("body").innerText()).slice(0,1500));
await page.reload({ waitUntil: "domcontentloaded" });
await page.waitForTimeout(6000);
const after = await page.locator("body").innerText();
console.log("SESSION AFTER RELOAD:", JSON.stringify(await page.evaluate(async () => (await fetch("/api/auth/session")).json())));
console.log("--- AFTER RELOAD ---\n" + after);
const leaks = ["canary-sandbox", "codeplanesmithers", "$5", "open issues", "demo-calendar", "smithers-demo", "pull request"].filter(k => after.includes(k));
console.log("LEAKS:", JSON.stringify(leaks));
// also localStorage residue
const ls = await page.evaluate(() => { const out: Record<string,number> = {}; for (let i=0;i<localStorage.length;i++){const k=localStorage.key(i)!; out[k]=(localStorage.getItem(k)??"").length;} return out; });
console.log("LOCALSTORAGE:", JSON.stringify(ls));
const lsAll = await page.evaluate(() => { let s=""; for (let i=0;i<localStorage.length;i++){s+=localStorage.getItem(localStorage.key(i)!)??"";} return s; });
console.log("LS LEAKS:", JSON.stringify(["canary-sandbox","codeplanesmithers","demo-calendar","open issues"].filter(k=>lsAll.includes(k))));
await page.screenshot({ path: "/tmp/canary-access/2.4-reload.png", fullPage: true });
await ctx.close();
