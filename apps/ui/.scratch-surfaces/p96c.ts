import { open, text, run } from "./drv.ts";
const { context, page, errors } = await open();
await page.waitForTimeout(4000);
const reqs: string[] = [];
page.on("request", (r) => { if (r.url().includes("/api/")) reqs.push(`${r.method()} ${r.url().replace("https://canary.smithers.sh","")}`); });
const cardBefore = await page.locator('article, [class*="card"]').count();
const idsBefore = await page.evaluate(() => Array.from(document.querySelectorAll('[data-card-id]')).map(e => e.getAttribute("data-card-id")));
console.log("cardIdsBefore", JSON.stringify(idsBefore));
await run(page, "/reco.refresh", 12000);
console.log("REQS", JSON.stringify(reqs, null, 1));
const idsAfter = await page.evaluate(() => Array.from(document.querySelectorAll('[data-card-id]')).map(e => e.getAttribute("data-card-id")));
console.log("cardIdsAfter", JSON.stringify(idsAfter));
console.log("TAIL>>>", (await text(page)).slice(-900));
await page.screenshot({ path: "/tmp/surfaces/9.6b.png" });
await context.close();
